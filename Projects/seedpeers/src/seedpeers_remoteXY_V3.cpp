const int PIN_Q1_SPECTRUM_1 = 19; // PWM Canale 1 (Rosso/Blu)
const int PIN_Q2_SPECTRUM_2 = 18; // PWM Canale 2 (Bianco)
const int PWM_FREQ = 5000;
const int PWM_RESOLUTION = 8;


void setLampState(int brightnessQ1, int brightnessQ2) {
    ledcWrite(PIN_Q1_SPECTRUM_1, brightnessQ1);
    ledcWrite(PIN_Q2_SPECTRUM_2, brightnessQ2);
}

void setup()
{
  Serial.begin(115200);

  RemoteXY_Init ();  // initialization by macros

  ledcAttach(PIN_Q1_SPECTRUM_1, PWM_FREQ, PWM_RESOLUTION);
  ledcAttach(PIN_Q2_SPECTRUM_2, PWM_FREQ, PWM_RESOLUTION);

  // Set sliders to their initial values AFTER RemoteXY_Init
  RemoteXY.Red_Blue_Slider = 0;
  RemoteXY.White_Slider    = 100;   // 100% white at startup

  setLampState(0, 255);

  Serial.println("Controller Lampada Piante (RemoteXY) Avviato!");
}

void loop()
{
  RemoteXYEngine.handler ();

  // Sliders are 0-100, PWM is 8 bit (0-255)
  setLampState(map(RemoteXY.Red_Blue_Slider, 0, 100, 0, 255),
               map(RemoteXY.White_Slider, 0, 100, 0, 255));

  // Bar variables are swapped relative to their on-screen labels in the GUI
  RemoteXY.Red_Blue_Bar = RemoteXY.Red_Blue_Slider;
  RemoteXY.White_Bar = RemoteXY.White_Slider;
}
